// Reference-vector generator for the avida-apto crate.
//
// Compiles against the real Apto library (libs/apto) and prints reference
// sequences that the Rust unit tests embed from ../testdata/. Build and run from
// the repository root:
//
//   c++ -std=c++11 -O2 -DNDEBUG -Ilibs/apto/include -Icbuild/libs/apto/include \
//       rust/avida-native/crates/apto/tools/ref_harness.cc cbuild/lib/libapto.a \
//       -o /tmp/apto_ref && /tmp/apto_ref sched > rust/avida-native/crates/apto/testdata/scheduler_ref.txt
//   /tmp/apto_ref rng > rust/avida-native/crates/apto/testdata/rng_ref.txt
//   /tmp/apto_ref acc > rust/avida-native/crates/apto/testdata/acc_ref.txt
//
// The operation stream fed to each scheduler is generated by a separate
// AvidaRNG ("driver") so the Rust tests can regenerate it exactly.

#include "apto/core/Array.h"
#include "apto/core/SmartPtr.h"
#include "apto/rng/AvidaRNG.h"
#include "apto/scheduler/Integrated.h"
#include "apto/scheduler/Probabilistic.h"
#include "apto/scheduler/ProbabilisticIntegrated.h"
#include "apto/scheduler/RoundRobin.h"
#include "apto/stat/Accumulator.h"

#include <cmath>
#include <cstdio>
#include <cstring>
#include <vector>

using namespace Apto;

static double DrawPriority(Random& drv, const std::vector<double>& chart, int id)
{
  switch (drv.GetInt(8)) {
    case 0: return 0.0;
    case 1: return drv.GetDouble();
    case 2: return static_cast<double>(drv.GetInt(1, 20));
    case 3: return drv.GetDouble(1.0, 1000.0);
    case 4: return static_cast<double>(drv.GetInt(1, 100000));
    case 5: {
      // Two statements: operand evaluation order of '*' is unspecified.
      const double e = pow(2.0, drv.GetInt(0, 40));
      return e * drv.GetDouble(1.0, 2.0);
    }
    case 6: return drv.GetDouble(1e9, 1e13);
    default: return chart[id];
  }
}

static void RunScenario(const char* name, PriorityScheduler& sched, int seed, int n, int steps)
{
  RNG::AvidaRNG drv(seed);
  std::vector<double> chart(n, 0.0);
  int live = 0;  // entries with priority >= 1

  printf("%s", name);
  for (int step = 0; step < steps; step++) {
    if (live == 0 || drv.GetInt(10) < 3) {
      const int id = drv.GetInt(n);
      const double p = DrawPriority(drv, chart, id);
      if (chart[id] >= 1.0) live--;
      if (p >= 1.0) live++;
      chart[id] = p;
      sched.AdjustPriority(id, p);
    } else {
      printf(" %d", sched.Next());
    }
  }
  printf("\n");
}

static void Sched()
{
  {
    Scheduler::RoundRobin s(20);
    RunScenario("roundrobin_s1_n20", s, 1, 20, 3000);
  }
  {
    Scheduler::Integrated s(50);
    RunScenario("integrated_s1_n50", s, 1, 50, 6000);
  }
  {
    Scheduler::Integrated s(7);
    RunScenario("integrated_s2_n7", s, 2, 7, 6000);
  }
  {
    RNG::AvidaRNG world(101);
    SmartPtr<Random> rng(new RNG::AvidaRNG(world.GetInt(0x7FFFFFFF)));
    Scheduler::Probabilistic s(50, rng);
    RunScenario("probabilistic_w101_s3_n50", s, 3, 50, 6000);
  }
  {
    RNG::AvidaRNG world(202);
    SmartPtr<Random> rng(new RNG::AvidaRNG(world.GetInt(world.MaxSeed())));
    Scheduler::ProbabilisticIntegrated s(50, rng);
    RunScenario("probint_w202_s4_n50", s, 4, 50, 6000);
  }
  {
    RNG::AvidaRNG world(303);
    SmartPtr<Random> rng(new RNG::AvidaRNG(world.GetInt(world.MaxSeed())));
    Scheduler::ProbabilisticIntegrated s(9, rng);
    RunScenario("probint_w303_s5_n9", s, 5, 9, 6000);
  }
}

static void PrintBits(double d)
{
  unsigned long long u;
  memcpy(&u, &d, sizeof(u));
  printf(" %016llx", u);
}

static void Rng()
{
  // Seeds include values above MAX_SEED (reduced modulo MAX_SEED) and 0.
  const int seeds[] = {0, 1, 42, 161803398, 161803399, 2147483647};
  for (int si = 0; si < 6; si++) {
    RNG::AvidaRNG r(seeds[si]);
    printf("seed %d %d %d", seeds[si], r.Seed(), r.OriginalSeed());
    for (int i = 0; i < 64; i++) PrintBits(r.GetDouble());
    printf("\n");
  }

  RNG::AvidaRNG r(12345);
  printf("uint"); for (int i = 0; i < 200; i++) printf(" %u", r.GetUInt(1000u + i)); printf("\n");
  printf("uint_range"); for (int i = 0; i < 200; i++) printf(" %u", r.GetUInt(5u, 5000u + i)); printf("\n");
  printf("int"); for (int i = 0; i < 200; i++) printf(" %d", r.GetInt(i - 100)); printf("\n");
  printf("int_range"); for (int i = 0; i < 200; i++) printf(" %d", r.GetInt(-50 - i, 50 + i)); printf("\n");
  printf("int_full"); for (int i = 0; i < 200; i++) printf(" %d", r.GetInt()); printf("\n");
  printf("p"); for (int i = 0; i < 400; i++) printf(" %d", r.P(i / 400.0) ? 1 : 0); printf("\n");
  printf("normal"); for (int i = 0; i < 200; i++) PrintBits(r.GetRandNormal()); printf("\n");
  printf("normal_mv"); for (int i = 0; i < 200; i++) PrintBits(r.GetRandNormal(i * 0.5, 1.0 + i)); printf("\n");
  printf("poisson"); for (int i = 0; i < 200; i++) printf(" %u", r.GetRandPoisson(i * 0.37)); printf("\n");
  // exp(-mean) underflows to 0 for mean > ~745: the C++ still draws once.
  printf("poisson_big"); for (int i = 0; i < 20; i++) { printf(" %u", r.GetRandPoisson(800.0 + i)); printf(" %u", r.GetUInt(1000000)); } printf("\n");
  printf("poisson_np"); for (int i = 0; i < 200; i++) printf(" %u", r.GetRandPoisson(10.0 + i, (i % 10) / 10.0 + 0.05)); printf("\n");
  printf("full_binomial"); for (int i = 0; i < 200; i++) printf(" %u", r.GetFullRandBinomial(i * 0.75, (i % 7) / 7.0)); printf("\n");
  printf("binomial");
  for (int i = 0; i < 300; i++) {
    double n = (i % 3 == 0) ? 5.0 + i : (i % 3 == 1 ? 1000.0 + 37.0 * i : 20.0 + 3.0 * i);
    double p = (i % 3 == 1) ? 0.0005 * ((i % 11) + 1) : ((i % 13) + 1) / 14.0;
    printf(" %u", r.GetRandBinomial(n, p));
  }
  printf("\n");
  printf("choose");
  for (int i = 1; i <= 40; i++) {
    Array<int> out(i % 8 + 1);
    r.Choose(i % 8 + 1 + (i % 5) * 3, out);
    printf(" |");
    for (int j = 0; j < out.GetSize(); j++) printf(" %d", out[j]);
  }
  printf("\n");
  printf("tail"); for (int i = 0; i < 20; i++) PrintBits(r.GetDouble()); printf("\n");
}

// One line per case: name count sum min max mean variance stderr (doubles as
// bit patterns), after each Add() of the case's values.
template <typename T> static void PrintAcc(const char* name, const Stat::Accumulator<T>& a)
{
  printf("%s %zu", name, a.Count());
  printf(" %s", "|");
  PrintBits((double)a.Sum());
  PrintBits((double)a.Min());
  PrintBits((double)a.Max());
  PrintBits(a.Mean());
  PrintBits(a.Variance());
  PrintBits(a.StdError());
  printf("\n");
}

static void Acc()
{
  {
    Stat::Accumulator<int> a;
    PrintAcc("int_empty", a);
    const int vals[] = {5, -3, 7, 7, 0, 100000, -46341, 2, 9};
    for (int i = 0; i < 9; i++) { a.Add(vals[i]); PrintAcc("int_seq", a); }
    a.Clear();
    PrintAcc("int_cleared", a);
    a.Add(4);
    PrintAcc("int_one", a);
  }
  {
    // Second moment overflows int: 50000^2 > INT_MAX.
    Stat::Accumulator<int> a;
    for (int i = 0; i < 5; i++) { a.Add(50000 + i); PrintAcc("int_overflow", a); }
  }
  {
    Stat::Accumulator<double> a;
    PrintAcc("dbl_empty", a);
    const double vals[] = {-1.5, -2.25, -0.125, 3.75, 1e10, 1e-10, 0.1, 0.2, 0.3};
    for (int i = 0; i < 9; i++) { a.Add(vals[i]); PrintAcc("dbl_seq", a); }
  }
  {
    RNG::AvidaRNG r(77);
    Stat::Accumulator<int> a;
    Stat::Accumulator<double> d;
    for (int i = 0; i < 200; i++) {
      const int v = r.GetInt(-1000, 1000);
      a.Add(v);
      d.Add(r.GetDouble(-5.0, 5.0));
    }
    PrintAcc("int_rand", a);
    PrintAcc("dbl_rand", d);
  }
}

int main(int argc, char** argv)
{
  if (argc < 2) { fprintf(stderr, "usage: %s sched|rng\n", argv[0]); return 1; }
  if (strcmp(argv[1], "sched") == 0) Sched();
  else if (strcmp(argv[1], "rng") == 0) Rng();
  else if (strcmp(argv[1], "acc") == 0) Acc();
  else return 1;
  return 0;
}
