//! The `cHardwareCPU` instruction library table (`cHardwareCPU::initInstLib`,
//! avida-core/source/cpu/cHardwareCPU.cc at 47f13dadb), generated from the
//! C++ `s_f_array`: name, handler method, class, flags and description of
//! each of the 563 entries, in library order.

use avida_genome::inst_lib::{inst_flag as F, InstructionClass as C};

/// One `tInstLibEntry<tMethod>`.
#[derive(Debug, Clone, Copy)]
pub struct CpuInstDef {
    /// Instruction name.
    pub name: &'static str,
    /// The `cHardwareCPU::Inst_*` (or `cHardwareBase::Inst_*`) handler.
    pub method: &'static str,
    /// `InstructionClass`
    pub class: C,
    /// `nInstFlag` bits
    pub flags: u32,
    /// Description.
    pub desc: &'static str,
}

const fn d(
    name: &'static str,
    method: &'static str,
    class: C,
    flags: u32,
    desc: &'static str,
) -> CpuInstDef {
    CpuInstDef {
        name,
        method,
        class,
        flags,
        desc,
    }
}

