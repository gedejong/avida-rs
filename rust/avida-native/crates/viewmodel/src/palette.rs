//! Colour lookup tables.
//!
//! * [`Palette::Viridis`] and [`Palette::Cividis`]: perceptually uniform
//!   sequential maps for continuous layers (van der Walt & Smith's viridis;
//!   Nuñez, Anderton & Renslow's cividis, which is also uniform for
//!   red-green colour-vision deficiency). The 256-entry tables are
//!   matplotlib 3.10's `viridis` and `cividis` rounded to 8 bits.
//! * [`Palette::OkabeIto`]: Okabe & Ito's colour-blind-safe categorical
//!   palette for the most abundant genotypes, without its black (which
//!   would read as an empty cell); every other genotype is grey.

/// An 8-bit sRGB colour with straight (non-premultiplied) alpha.
pub type Rgba = [u8; 4];

/// The colour of an empty cell: fully transparent, so a front end shows its
/// own background.
pub const EMPTY: Rgba = [0, 0, 0, 0];

/// Number of genotype colours before falling back to [`OTHER_GREY`].
pub const CATEGORICAL_SLOTS: usize = 7;

/// Okabe-Ito without black: orange, sky blue, bluish green, yellow, blue,
/// vermillion, reddish purple.
pub const OKABE_ITO: [[u8; 3]; CATEGORICAL_SLOTS] = [
    [0xE6, 0x9F, 0x00],
    [0x56, 0xB4, 0xE9],
    [0x00, 0x9E, 0x73],
    [0xF0, 0xE4, 0x42],
    [0x00, 0x72, 0xB2],
    [0xD5, 0x5E, 0x00],
    [0xCC, 0x79, 0xA7],
];

/// The grey of the extended Okabe-Ito set, for genotypes outside the top
/// [`CATEGORICAL_SLOTS`].
pub const OTHER_GREY: [u8; 3] = [0x99, 0x99, 0x99];

/// A colour map.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Palette {
    /// Sequential, dark purple to yellow.
    #[default]
    Viridis,
    /// Sequential, dark blue to yellow.
    Cividis,
    /// Categorical, [`CATEGORICAL_SLOTS`] colours plus grey.
    OkabeIto,
}

const fn opaque(c: [u8; 3]) -> Rgba {
    [c[0], c[1], c[2], 255]
}

impl Palette {
    /// True for [`Palette::OkabeIto`].
    pub fn is_categorical(self) -> bool {
        matches!(self, Palette::OkabeIto)
    }

    /// The colour table: 256 entries for the sequential maps, the
    /// [`CATEGORICAL_SLOTS`] colours for the categorical one.
    pub fn table(self) -> &'static [[u8; 3]] {
        match self {
            Palette::Viridis => &VIRIDIS,
            Palette::Cividis => &CIVIDIS,
            Palette::OkabeIto => &OKABE_ITO,
        }
    }

    /// The colour at position `t` in `[0, 1]` (clamped). A sequential map
    /// uses matplotlib's lookup, entry `floor(t * 256)` capped at 255; the
    /// categorical palette splits `[0, 1]` into [`CATEGORICAL_SLOTS`] equal
    /// bins. NaN gives [`EMPTY`].
    pub fn sample(self, t: f64) -> Rgba {
        if t.is_nan() {
            return EMPTY;
        }
        let t = t.clamp(0.0, 1.0);
        let table = self.table();
        let n = table.len();
        let i = ((t * n as f64) as usize).min(n - 1);
        opaque(table[i])
    }

    /// The colour of categorical slot `slot` (a genotype's rank among the
    /// most abundant). `None` or a slot past [`CATEGORICAL_SLOTS`] is
    /// [`OTHER_GREY`]. A sequential map gives evenly spaced samples, so a
    /// front end can colour genotypes with it too.
    pub fn category(self, slot: Option<usize>) -> Rgba {
        match slot {
            Some(s) if s < CATEGORICAL_SLOTS => match self {
                Palette::OkabeIto => opaque(OKABE_ITO[s]),
                _ => self.sample(s as f64 / (CATEGORICAL_SLOTS - 1) as f64),
            },
            _ => opaque(OTHER_GREY),
        }
    }

    /// A 256-entry RGBA table of [`Palette::sample`] at `i / 255`, for
    /// front ends that colour on the GPU or cache the lookup.
    pub fn lut256(self) -> Vec<Rgba> {
        (0..256)
            .map(|i| self.sample(f64::from(i) / 255.0))
            .collect()
    }
}

